package com.example.pelletswaterheater.utils

import android.content.Context
import android.net.Uri
import androidx.core.content.FileProvider
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.TimeZone

/**
 * Interface for logging temperature data to CSV files.
 */
interface TemperatureLogger {
    /**
     * Logs a map of converted values to a CSV file as a single row with a given timestamp.
     *
     * @param values Map of field keys to converted values.
     * @param keyOrder List of keys in server order for consistent column ordering.
     * @param timestamp The batch timestamp (ISO 8601 format, second-level). Only used for testing, set internally otherwise.
     */
    fun logValues(values: Map<String, ConvertedValue>, keyOrder: List<String>, timestamp: String? = null)

    /**
     * Retrieves the URI of the latest log file for sharing.
     *
     * @param context The application context.
     * @return The URI of the latest log file or null if none exists.
     */
    fun getLatestLogUri(context: Context): Uri?
}

/**
 * Implementation of [TemperatureLogger] that logs to CSV files with FileProvider support.
 */
class TemperatureLoggerImpl(
    private val contextProvider: ContextProvider,
    private val logger: ILogger = Logger
) : TemperatureLogger {
    private val TAG = TemperatureLoggerImpl::class.java.simpleName
    private val maxFileSizeBytes = 5 * 1024 * 1024 // 5MB
    private val commentHeader = "# File generated by PelletsWaterHeater app see https://github.com/whatever/pelletswaterheater\n"

    override fun logValues(
        values: Map<String, ConvertedValue>,
        keyOrder: List<String>,
        timestamp: String?
    ) {
        try {
            val actualTimestamp = timestamp ?: isoTimestamp()
            val context = contextProvider.getContext()
            val logDir = File(context.filesDir, "logs")
            if (!logDir.exists()) logDir.mkdirs()

            val logFile = getCurrentLogFile(logDir)
            // Check file size and rotate if needed
            if (logFile.length() >= maxFileSizeBytes) {
                rotateLogFile(logDir, logFile, values, keyOrder)
            }

            if (!logFile.exists()) {
                writeHeaders(logFile, values, keyOrder)
            }

            // Write values as a single row
            val csvRow = buildCsvRow(actualTimestamp, values, keyOrder)
            logFile.appendText(csvRow, Charsets.UTF_8)
        } catch (e: Exception) {
            logger.e(TAG, "Failed to log values: $e", e)
        }
    }

    fun isoTimestamp(): String {
        val sdf = SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", Locale.US)
        sdf.timeZone = TimeZone.getTimeZone("UTC")
        return sdf.format(Date())
    }

    override fun getLatestLogUri(context: Context): Uri? {
        return try {
            val logDir = File(context.filesDir, "logs")
            val latestFile = logDir.listFiles()?.filter { it.name.endsWith(".csv") }
                ?.maxByOrNull { it.lastModified() }
            if (latestFile != null && latestFile.exists()) {
                FileProvider.getUriForFile(
                    context,
                    "${context.packageName}.fileprovider",
                    latestFile
                )
            } else {
                null
            }
        } catch (e: Exception) {
            logger.e(TAG, "Failed to get latest log URI: $e", e)
            null
        }
    }

    private fun getCurrentLogFile(logDir: File): File {
        return File(logDir, "temp_log.csv")
    }

    private fun writeHeaders(logFile: File, values: Map<String, ConvertedValue>, keyOrder: List<String>) {
        val sections = keyOrder.map { it.substringBeforeLast(".") }.distinct()
        val sectionHeader = sections.joinToString("") { section ->
            val fieldCount = keyOrder.count { it.startsWith("$section.") }
            ",$section${",".repeat(fieldCount - 1)}"
        }
        val fieldHeader = keyOrder.joinToString(",") { it.substringAfterLast(".") }
        val nameHeader = keyOrder.joinToString(",") { values[it]?.name ?: "" }
        val unitHeader = keyOrder.joinToString(",") { values[it]?.unit ?: "" }
        val header = "${commentHeader}Machine parts:$sectionHeader\n,$fieldHeader\n,$nameHeader\ntimestamp,$unitHeader\n"
        logFile.writeText(header, Charsets.UTF_8)
    }

    private fun rotateLogFile(
        logDir: File,
        currentFile: File,
        values: Map<String, ConvertedValue>,
        keyOrder: List<String>
    ) {
        try {
            val index = logDir.listFiles()
                ?.filter { it.name.startsWith("temp_log_") && it.name.endsWith(".csv") }
                ?.map { it.name.substringAfter("temp_log_").substringBefore(".csv").toIntOrNull() ?: 0 }
                ?.maxOrNull() ?: 0
            val newFile = File(logDir, "temp_log_${index + 1}.csv")
            currentFile.renameTo(newFile)
        } catch (e: Exception) {
            logger.e(TAG, "Failed to rotate log file: $e", e)
        }
    }

    private fun buildCsvRow(timestamp: String, values: Map<String, ConvertedValue>, keyOrder: List<String>): String {
        val fields = keyOrder.map { key ->
            val value = values[key]
            if (value == null) {
                logger.w(TAG, "Missing value for key: $key")
                ""
            } else {
                value.logical
            }
        }
        return "$timestamp,${fields.joinToString(",")}\n"
    }
}